"""Regenerate js/portrait-data.js from the portrait cut-out.

Run from the project root:
    python tools/build_portrait_data.py
Requires Python 3, Pillow and NumPy:
    pip install pillow numpy
"""
import base64
import os
import sys

import numpy as np
from PIL import Image, ImageFilter

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "assets", "images", "aditya-gaur-cutout.png")
OUT = os.path.join(ROOT, "js", "portrait-data.js")
GW = 176  # dot-grid width; higher gives more detail and more dots


def build():
    im = Image.open(SRC).convert("RGBA")
    al = np.asarray(im)[..., 3]
    ys, xs = np.where(al > 40)
    im = im.crop((xs.min(), ys.min(), xs.max() + 1, ys.max() + 1))
    gh = round(GW * im.height / im.width)
    a = np.asarray(im).astype(np.float64)
    alpha = a[..., 3] / 255.0

    def resize(arr):
        return np.asarray(Image.fromarray(arr.astype(np.float32), mode="F").resize((GW, gh), Image.BOX))

    A = resize(alpha)
    P = np.stack([resize(a[..., k] * alpha) for k in range(3)], -1)
    C = P / np.maximum(A[..., None], 1e-3)
    lum = np.clip((0.299 * C[..., 0] + 0.587 * C[..., 1] + 0.114 * C[..., 2]) / 255, 0, 1)
    bl = np.asarray(Image.fromarray((lum * 255).astype(np.uint8)).filter(ImageFilter.GaussianBlur(3.2))).astype(float) / 255
    det = np.clip(lum + 1.5 * (lum - bl), 0, 1)
    b = np.clip(np.power(det, 0.46) * 1.1, 0, 1)
    out = np.where(A > 0.5, 10 + np.round(b * 245), 0).astype(np.uint8)
    return GW, gh, out


if __name__ == "__main__":
    w, h, out = build()
    dest = sys.argv[1] if len(sys.argv) > 1 else OUT
    data = base64.b64encode(out.tobytes()).decode()
    with open(dest, "w") as f:
        f.write("/* Generated by tools/build_portrait_data.py from assets/images/aditya-gaur-cutout.png */\n")
        f.write('window.PORTRAIT_DOTS={w:%d,h:%d,d:"%s"};\n' % (w, h, data))
    print("wrote", dest, "grid", w, "x", h, "dots", int((out > 0).sum()))
